package com.cie.tickets;

import com.cie.jira.JiraClient;
import com.cie.model.Models.*;
import com.cie.store.ArtifactStore;
import com.cie.summary.EvidenceSummarizer;
import org.springframework.http.HttpStatus;
import org.springframework.stereotype.Service;
import org.springframework.web.server.ResponseStatusException;

import java.util.*;

/**
 * Owns the ticket lifecycle and enforces the rule the whole project rests on:
 * the system drafts, a person decides.
 *
 *   createDraft  cluster -> summary -> DRAFT          (one open ticket per cluster = duplicate guard)
 *   update       analyst edits wording                 (DRAFT only)
 *   approve      explicit human action -> Jira        (DRAFT/APPROVED -> CREATED; idempotent)
 *   reject       discard
 *
 * Prototype limits: tickets live in memory (lost on restart) and there is no login, so audit
 * entries say "analyst". Add persistence and Spring Security to attribute actions to real people.
 */
@Service
public class TicketService {
    private static final String NEXT_STEPS =
            "Review logs and the relevant workflows, attempt to reproduce, and define tests before proposing any fix.";

    private final ArtifactStore store;
    private final EvidenceSummarizer summarizer;
    private final JiraClient jira;
    private final Map<String, Ticket> tickets = new LinkedHashMap<>();   // guarded by `this`

    public TicketService(ArtifactStore store, EvidenceSummarizer summarizer, JiraClient jira) {
        this.store = store;
        this.summarizer = summarizer;
        this.jira = jira;
    }

    public synchronized Ticket createDraft(int clusterId) {
        Optional<Ticket> open = tickets.values().stream()
                .filter(t -> t.clusterId() == clusterId && t.status() != TicketStatus.REJECTED)
                .findFirst();
        if (open.isPresent()) return open.get();

        Cluster c = store.cluster(clusterId)
                .orElseThrow(() -> new ResponseStatusException(HttpStatus.NOT_FOUND, "No cluster " + clusterId));
        List<Complaint> evidence = c.representativeIds().stream()
                .map(store::complaint).flatMap(Optional::stream).toList();
        Summary s = summarizer.summarize(c, evidence, store.trend(clusterId));

        String topIssue = c.topIssues().isEmpty() ? "mixed issues" : c.topIssues().get(0).name();
        Ticket t = new Ticket(UUID.randomUUID().toString().substring(0, 8), clusterId, TicketStatus.DRAFT,
                "Investigate recurring complaints about " + c.label() + " (" + topIssue + ")",
                s.observedPattern(), s.hypothesis(), NEXT_STEPS, s.citedComplaintIds(), null,
                List.of(Ticket.stamp("Draft generated by " + summarizer.getClass().getSimpleName())));
        return save(t);
    }

    public synchronized List<Ticket> list() {
        return List.copyOf(tickets.values());
    }

    public synchronized Ticket get(String id) {
        Ticket t = tickets.get(id);
        if (t == null) throw new ResponseStatusException(HttpStatus.NOT_FOUND, "No ticket " + id);
        return t;
    }

    public synchronized Ticket update(String id, TicketEdit edit) {
        Ticket t = get(id);
        if (t.status() != TicketStatus.DRAFT) {
            throw new ResponseStatusException(HttpStatus.CONFLICT, "Only drafts can be edited");
        }
        if (edit.title() == null || edit.title().isBlank()) {
            throw new ResponseStatusException(HttpStatus.BAD_REQUEST, "Title is required");
        }
        return save(t.edited(edit));
    }

    public synchronized Ticket approve(String id) {
        Ticket t = get(id);
        if (t.status() == TicketStatus.CREATED) return t;                       // idempotent
        if (t.status() == TicketStatus.REJECTED) {
            throw new ResponseStatusException(HttpStatus.CONFLICT, "Rejected tickets cannot be approved");
        }
        t = save(t.transition(TicketStatus.APPROVED, null, "Approved by analyst"));
        try {
            String key = jira.createIssue(t);
            return save(t.transition(TicketStatus.CREATED, key, "Jira issue created: " + key));
        } catch (RuntimeException e) {
            save(t.transition(TicketStatus.APPROVED, null, "Jira creation failed: " + e.getMessage()));
            throw new ResponseStatusException(HttpStatus.BAD_GATEWAY,
                    "Jira creation failed. The ticket stays approved, so you can retry.");
        }
    }

    public synchronized Ticket reject(String id) {
        Ticket t = get(id);
        if (t.status() == TicketStatus.CREATED) {
            throw new ResponseStatusException(HttpStatus.CONFLICT, "A created ticket cannot be rejected here");
        }
        return save(t.transition(TicketStatus.REJECTED, null, "Rejected by analyst"));
    }

    private Ticket save(Ticket t) {
        tickets.put(t.id(), t);
        return t;
    }
}
